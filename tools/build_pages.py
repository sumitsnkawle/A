#!/usr/bin/env python3
"""Build one static page per language from _source/index.html.

Search engines index the text that is in a page's HTML, at the page's own
address. The source page holds the text of all 12 languages in its
`translations` dictionary and fills it in with JavaScript, so only English
could ever be indexed. This script writes a real page for each language:

    index.html        English  (https://axionast.com/)
    ar/index.html     Arabic   (https://axionast.com/ar/)
    de/index.html     German   ... and so on

Each page gets its translated text written into the HTML, its own <html lang>
and text direction, a translated <title> and description, a canonical link,
hreflang links to every other language, and only its own translations (plus
English as fallback) instead of all 12. sitemap.xml lists every page.

Usage:  python3 tools/build_pages.py     (also rebuilds styles.css first)

Edit _source/index.html, never the generated pages: they are overwritten.
(GitHub Pages does not publish folders starting with "_", so the source
itself is never served.)
"""
import html
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "_source" / "index.html"
SITE = "https://axionast.com"

# Language code -> Open Graph locale. English is the default (served at /).
LOCALES = {
    "en": "en_GB", "ar": "ar_AE", "de": "de_DE", "fr": "fr_FR", "es": "es_ES", "ru": "ru_RU",
    "it": "it_IT", "pt": "pt_PT", "zh": "zh_CN", "ja": "ja_JP", "hi": "hi_IN", "ko": "ko_KR",
}
RTL = {"ar"}
# Other source pages (English only) and where they are published
STATIC_PAGES = {"privacy.html": "privacy/index.html", "404.html": "404.html"}
GENERATED_NOTE = "<!-- Generated by tools/build_pages.py from _source/index.html. Edit the source, then run the build. -->"


def url(lang, path=""):
    """Address of a page in a language; path is "" for the homepage, "why/" for the Why page."""
    return (f"{SITE}/" if lang == "en" else f"{SITE}/{lang}/") + path


def home(lang):
    return "/" if lang == "en" else f"/{lang}/"


# Pages built for every language: path -> (main content source, title key, description key)
PAGES = {"": (None, None, "hero.desc"), "why/": ("why.html", "why.metaTitle", "why.metaDesc")}


def parse_translations(src):
    """Return ({lang: {key: text}}, (start, end) of each language block)."""
    start = src.index("const translations = {")
    end = src.index("\n};", start)
    body = src[start:end]
    dicts, spans = {}, {}
    for m in re.finditer(r"\n([a-z]{2}): \{(.*?)\n\}", body, re.S):
        lang = m.group(1)
        pairs = re.findall(r'"([A-Za-z0-9_.]+)":"((?:[^"\\]|\\.)*)"', m.group(2))
        # Values are JavaScript string literals; JSON rejects \' so unescape it first.
        dicts[lang] = {k: json.loads('"' + v.replace("\\'", "'") + '"') for k, v in pairs}
        spans[lang] = (start + m.start(), start + m.end())
    missing = set(LOCALES) - set(dicts)
    if missing:
        sys.exit(f"Languages missing from the translations dictionary: {sorted(missing)}")
    return dicts, spans


def t(dicts, lang, key):
    return dicts[lang].get(key, dicts["en"].get(key, key))


def structured_data(dicts, lang, title, desc, founder=True, path=""):
    """schema.org JSON-LD for the page: company, website, page, product and FAQ."""
    org, app = f"{SITE}/#organization", f"{SITE}/#software"
    faq = []
    for n in range(1, 13):
        q, a = t(dicts, lang, f"faq.q{n}"), t(dicts, lang, f"faq.a{n}")
        if q != f"faq.q{n}":
            faq.append({"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}})
    graph = {
        "@context": "https://schema.org",
        "@graph": [
            {"@type": "Organization", "@id": org, "name": "Axion Consultancy Services", "url": f"{SITE}/",
             "logo": f"{SITE}/AxionLogo.png", "email": "info@axionast.com",
             "address": {"@type": "PostalAddress", "addressCountry": "AE"},
             "contactPoint": {"@type": "ContactPoint", "contactType": "sales", "email": "info@axionast.com"}},
            {"@type": "WebSite", "@id": f"{url(lang)}#website", "url": url(lang), "name": "Axion Regulus",
             "inLanguage": lang, "publisher": {"@id": org}},
            {"@type": "WebPage", "@id": f"{url(lang)}#webpage", "url": url(lang), "name": title, "description": desc,
             "inLanguage": lang, "isPartOf": {"@id": f"{url(lang)}#website"}, "about": {"@id": app},
             "primaryImageOfPage": f"{SITE}/team-review.jpg"},
            {"@type": "SoftwareApplication", "@id": app, "name": "Axion Regulus",
             "applicationCategory": "BusinessApplication", "operatingSystem": "Web", "description": desc,
             "publisher": {"@id": org}, "availableLanguage": list(LOCALES)},
            {"@type": "FAQPage", "@id": f"{url(lang)}#faq", "inLanguage": lang, "mainEntity": faq},
        ],
    }
    if path:
        graph["@graph"] = [graph["@graph"][0],
                           {"@type": "WebPage", "@id": f"{url(lang, path)}#webpage", "url": url(lang, path), "name": title,
                            "description": desc, "inLanguage": lang, "isPartOf": {"@id": f"{url(lang)}#website"},
                            "about": {"@id": app}}]
    if founder:
        graph["@graph"][0]["founder"] = {"@id": f"{SITE}/#founder"}
        graph["@graph"].insert(1, {"@type": "Person", "@id": f"{SITE}/#founder", "name": "Anastasiia Bolotna",
                                   "jobTitle": t(dicts, lang, "founder.cardTitle"),
                                   "worksFor": {"@id": org}, "url": f"{url(lang)}#founder"})
    # Escape "<" so no value can close the <script> element early
    return json.dumps(graph, ensure_ascii=False, indent=1).replace("<", "\\u003c")


VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}


def bake_text(page, dicts, lang):
    """Write each [data-i18n] element's translated text into the HTML.

    Mirrors applyLanguage(), which sets the element's textContent, so an
    element's children are replaced by the translated text.
    """
    # Never touch <script> contents
    masked = re.sub(r"<script\b.*?</script>", lambda m: "\0" * len(m.group(0)), page, flags=re.S)
    out, pos = [], 0
    start_tag = re.compile(r'<([a-zA-Z][a-zA-Z0-9]*)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>')
    while True:
        m = start_tag.search(masked, pos)
        if not m:
            break
        tag, key = m.group(1).lower(), m.group(2)
        # Find the matching closing tag, counting nested tags of the same name
        depth, i = 1, m.end()
        tok = re.compile(rf"<(/?){tag}\b[^>]*?(/?)>", re.I)
        while depth:
            n = tok.search(masked, i)
            if not n:
                sys.exit(f"No closing </{tag}> for data-i18n=\"{key}\"")
            if n.group(1):
                depth -= 1
            elif not n.group(2) and tag not in VOID:
                depth += 1
            i = n.end()
        close_start = n.start()
        out.append(page[pos:m.end()])
        out.append(html.escape(t(dicts, lang, key), quote=False))
        pos = close_start
    out.append(page[pos:])
    page = "".join(out)

    def placeholder(m):
        tag = m.group(0)
        key = re.search(r'data-i18n-placeholder="([^"]+)"', tag).group(1)
        text = html.escape(t(dicts, lang, key), quote=True)
        return re.sub(r'placeholder="[^"]*"', f'placeholder="{text}"', tag)

    return re.sub(r"<(?:input|textarea)\b[^>]*data-i18n-placeholder=\"[^\"]+\"[^>]*>", placeholder, page)


def set_meta(page, dicts, lang, path=""):
    def attr(pattern, value):
        nonlocal page
        value = html.escape(value, quote=True)
        page, n = re.subn(pattern, lambda m: m.group(1) + value + m.group(2), page, count=1)
        if n != 1:
            sys.exit(f"Could not find {pattern!r} in the source <head>")

    title_key, desc_key = PAGES[path][1], PAGES[path][2]
    if title_key:
        title = t(dicts, lang, title_key)
    elif lang == "en":
        title = re.search(r"<title>(.*?)</title>", page).group(1)
        title = html.unescape(title)
    else:
        # "AI-powered Enterprise Compliance Intelligence — AI with Supervision." -> first part
        tagline = re.split(r"\s*—+\s*", t(dicts, lang, "footer.tagline"))[0].strip()
        title = f"Axion Regulus | {tagline}"
    desc = t(dicts, lang, desc_key)

    page = re.sub(r"<title>.*?</title>", f"<title>{html.escape(title, quote=False)}</title>", page, count=1)
    ld = structured_data(dicts, lang, title, desc, founder="founder" not in HIDDEN and not path, path=path)
    page, n = re.subn(r'<script type="application/ld\+json">.*?</script>',
                      lambda m: f'<script type="application/ld+json">\n{ld}\n</script>', page, count=1, flags=re.S)
    if n != 1:
        sys.exit("Could not find the JSON-LD <script> in the source <head>")
    attr(r'(<meta name="description" content=")[^"]*(">)', desc)
    attr(r'(<meta property="og:title" content=")[^"]*(">)', title)
    attr(r'(<meta property="og:description" content=")[^"]*(">)', desc)
    attr(r'(<meta property="og:url" content=")[^"]*(">)', url(lang, path))
    attr(r'(<meta name="twitter:title" content=")[^"]*(">)', title)
    attr(r'(<meta name="twitter:description" content=")[^"]*(">)', desc)
    attr(r'(<link rel="canonical" href=")[^"]*(">)', url(lang, path))

    # Search engines ignore meta keywords
    page = re.sub(r'<meta name="keywords"[^>]*>\n', "", page)

    # og:locale for this page, the others as alternates
    locales = f'<meta property="og:locale" content="{LOCALES[lang]}">\n' + "".join(
        f'<meta property="og:locale:alternate" content="{loc}">\n' for code, loc in LOCALES.items() if code != lang)
    page, n = re.subn(r'<meta property="og:locale" content="[^"]*">\n(?:<meta property="og:locale:alternate" content="[^"]*">\n)*',
                      locales, page, count=1)
    if n != 1:
        sys.exit("Could not find the og:locale tags in the source <head>")

    # hreflang: every language version, plus x-default for everyone else
    alternates = "".join(f'<link rel="alternate" hreflang="{code}" href="{url(code, path)}">\n' for code in LOCALES)
    alternates += f'<link rel="alternate" hreflang="x-default" href="{url("en", path)}">\n'
    page = re.sub(r'(<link rel="canonical" href="[^"]*">\n)', lambda m: m.group(1) + alternates, page, count=1)

    # <html lang="…" dir="…">
    page, n = re.subn(r'<html lang="[^"]*"', f'<html lang="{lang}" dir="{"rtl" if lang in RTL else "ltr"}"' + (f' data-page="{path}"' if path else ''), page, count=1)
    if n != 1:
        sys.exit("Could not find <html lang> in the source")
    return page


def root_relative_assets(page):
    """Pages in /xx/ must load styles and images from the site root."""
    def fix(m):
        return f'{m.group(1)}="/{m.group(2)}"'
    # Only markup: script code builds its own (already root-relative) links
    parts = re.split(r"(<script\b.*?</script>)", page, flags=re.S)
    return "".join(p if p.startswith("<script") else
                   re.sub(r'\b(src|srcset|href)="(?!#|/|https?:|mailto:|tel:|data:)([^"]+)"', fix, p)
                   for p in parts)


def keep_languages(page, spans, lang):
    """Drop the other languages' translations from the page's script."""
    keep = {"en", lang}
    for code, (a, b) in sorted(spans.items(), key=lambda kv: -kv[1][0]):
        if code in keep:
            continue
        # Remove the block and the comma that separates it from its neighbour
        before = page[:a]
        if before.endswith(","):
            before = before[:-1]
        page = before + page[b:]
    # Tidy a trailing comma left before the closing brace
    return re.sub(r"\},(\n\};)", r"}\1", page)


def drop_drafts(src):
    """Leave out anything marked data-draft (e.g. a section that isn't ready to publish).

    For a hidden <section id="x" data-draft>, also leave out its script code
    (between "// draft:x" and "// end draft:x") and its translations
    ("x.*" and "nav.x"), so none of its content is in the published page.
    Returns the source and the ids of the hidden sections.
    """
    hidden = re.findall(r'<section id="([\w-]+)"[^>]*\sdata-draft\b', src)
    src, sections = re.subn(r"<!-- [^\n]*-->\n<section\b[^>]*\sdata-draft\b.*?</section>\n\n", "", src, flags=re.S)
    src, lines = re.subn(r"\n[^\n]*<(?:a|li)\b[^>]*\sdata-draft\b[^\n]*", "", src)
    for sid in hidden:
        src = re.sub(rf"\n// draft:{sid}\n.*?\n// end draft:{sid}\n", "\n", src, flags=re.S)
        entry = rf'"(?:{sid}\.[A-Za-z0-9_]+|nav\.{sid})":"(?:[^"\\]|\\.)*"'
        src = re.sub(rf"(?m)^{entry},?", "", src)
        src = re.sub(rf",{entry}", "", src)
    if sections or lines:
        print(f"left out drafts: {sections} section(s) {hidden}, {lines} link(s)")
    return src, set(hidden)


HIDDEN = set()  # ids of sections left out of this build


def build():
    global HIDDEN
    src, HIDDEN = drop_drafts(SOURCE.read_text(encoding="utf-8"))
    dicts, spans = parse_translations(src)
    for path, (content, _, _) in PAGES.items():
        page_src = src
        if content:
            # Same header, footer and scripts as the homepage, with this page's own <main>
            main = (ROOT / "_source" / content).read_text(encoding="utf-8")
            main = re.sub(r"\A<!--.*?-->\n", "", main, flags=re.S)
            a = page_src.index('<main id="main">\n') + len('<main id="main">\n')
            page_src = page_src[:a] + main + page_src[page_src.index("</main>", a):]
        for lang in LOCALES:
            build_page(page_src, spans if not content else None, dicts, lang, path)


def build_page(page_src, spans, dicts, lang, path):
    if spans is None:
        spans = parse_translations(page_src)[1]
    page = keep_languages(page_src, spans, lang)
    page = bake_text(page, dicts, lang)
    page = set_meta(page, dicts, lang, path)
    # Links to other pages: the Why page in this language, and homepage sections from other pages
    page = page.replace('href="why/"', f'href="{home(lang)}why/"')
    if path:
        page = re.sub(r'href="#(?!main")', f'href="{home(lang)}#', page)
        page = re.sub(r"href: '#", f"href: '{home(lang)}#", page)
    if lang != "en" or path:
        page = root_relative_assets(page)
    page = page.replace("<!DOCTYPE html>\n", f"<!DOCTYPE html>\n{GENERATED_NOTE}\n", 1)
    out = ROOT / (("" if lang == "en" else f"{lang}/") + path + "index.html")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {len(page.encode()) // 1024} KB")


def build_static():
    # Single-language pages, published as they are
    for name, out in STATIC_PAGES.items():
        dest = ROOT / out
        dest.parent.mkdir(exist_ok=True)
        page = (ROOT / "_source" / name).read_text(encoding="utf-8")
        dest.write_text(page.replace("<!DOCTYPE html>\n", f"<!DOCTYPE html>\n{GENERATED_NOTE.replace('index.html', name)}\n", 1), encoding="utf-8")
        print(f"{out}: {len(page.encode()) // 1024} KB")

    today = date.today().isoformat()
    entries = ""
    for path in PAGES:
        links = "".join(f'    <xhtml:link rel="alternate" hreflang="{c}" href="{url(c, path)}"/>\n' for c in LOCALES)
        links += f'    <xhtml:link rel="alternate" hreflang="x-default" href="{url("en", path)}"/>\n'
        entries += "".join(f"  <url>\n    <loc>{url(c, path)}</loc>\n    <lastmod>{today}</lastmod>\n{links}  </url>\n" for c in LOCALES)
    entries += f"  <url>\n    <loc>{SITE}/privacy/</loc>\n    <lastmod>{today}</lastmod>\n  </url>\n"
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        f"{entries}</urlset>\n", encoding="utf-8")
    print(f"sitemap.xml: {len(LOCALES) * len(PAGES) + 1} pages")


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import build_css
    build_css.main()
    build()
    build_static()
